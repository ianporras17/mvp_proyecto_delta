import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
test.use({ trace: 'off' });
test('T49 Docker storage survives restart and catalog downloads identical bytes', async ({ page, request }) => {
  test.skip(process.env.RUN_T49_STORAGE !== '1');
  test.setTimeout(120_000);
  const endpoint = 'http://localhost:8200/api/v1/results';
  const before = await (await request.get(endpoint)).json();
  expect(before.length).toBeGreaterThan(0);
  const item = before[0];
  execFileSync('docker', ['compose', 'restart', 'result-storage'], { cwd: path.resolve('..'), timeout: 30_000 });
  await expect.poll(async () => { try { return (await request.get(endpoint)).status(); } catch { return 0; } }).toBe(200);
  const after = await (await request.get(endpoint)).json();
  expect(after.find((r: { id: string }) => r.id === item.id).sha256).toBe(item.sha256);
  await page.goto('http://localhost:8081');
  await expect(page.getByRole('heading', { name: 'Videos anonimizados' })).toBeVisible();
  const pending = page.waitForEvent('download');
  await page.locator(`a[href$="/${item.id}/download"]`).click();
  const download = await pending;
  const destination = path.resolve('../.runtime/t49-evidence/persistence-download.mp4');
  await download.saveAs(destination);
  const bytes = await fs.readFile(destination);
  expect(bytes.length).toBe(item.size);
  expect(createHash('sha256').update(bytes).digest('hex')).toBe(item.sha256);
  await fs.writeFile(path.resolve('../.runtime/t49-evidence/persistence.json'), JSON.stringify({ result: item.id, bytes: bytes.length, sha256: item.sha256, restarted: true, catalogDownload: true }, null, 2));
});
